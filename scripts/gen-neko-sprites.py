#!/usr/bin/env python3
"""Generate src/ui/neko-sprites.ts from oneko's XBM bitmaps.

Usage: python3 -I scripts/gen-neko-sprites.py <oneko-checkout> > src/ui/neko-sprites.ts
       python3 -I scripts/gen-neko-sprites.py <oneko-checkout> --preview name [name...]

Source: oneko 1.2.sakura (https://github.com/tie/oneko), bitmaps/neko + bitmasks/neko.
Public domain per Debian's debian/copyright for oneko. Art lineage: NEKO.COM (Naoshi
Watanabe), NekoDA (Kenji Gotoh), xneko (Masayuki Koba), oneko (Tatsuya Kato).
"""
import re
import sys
from pathlib import Path

SIZE = 32

# Our cat modes → oneko frames. run/scratch have one sequence per direction.
FRAMES = {
    "sleep": ["sleep1", "sleep2"],
    "runRight": ["right1", "right2"],
    "runLeft": ["left1", "left2"],
    "sit": ["mati2"],
    "wash": ["jare2", "mati2"],
    "alert": ["awake"],
    "scratch": ["kaki1", "kaki2"],
}


def read_xbm(path: Path) -> list[int]:
    text = path.read_text()
    body = text[text.index("{") + 1 : text.rindex("}")]
    return [int(b, 16) for b in re.findall(r"0x[0-9a-fA-F]{2}", body)]


def bit(data: list[int], x: int, y: int) -> bool:
    row_bytes = SIZE // 8
    return bool(data[y * row_bytes + x // 8] >> (x % 8) & 1)  # XBM is LSB-first


def frame(root: Path, name: str) -> list[str]:
    bits = read_xbm(root / "bitmaps" / "neko" / f"{name}.xbm")
    mask = read_xbm(root / "bitmasks" / "neko" / f"{name}_mask.xbm")
    rows = []
    for y in range(SIZE):
        row = ""
        for x in range(SIZE):
            row += "k" if bit(bits, x, y) else "w" if bit(mask, x, y) else "."
        rows.append(row)
    return rows


def emit(root: Path) -> str:
    out = [
        "// Generated by scripts/gen-neko-sprites.py from oneko's XBM bitmaps. Do not edit.",
        "// Public domain (Debian debian/copyright for oneko). Art by Naoshi Watanabe,",
        "// Kenji Gotoh, Masayuki Koba and Tatsuya Kato.",
        "import type { CatMode } from './neko-logic.ts';",
        "",
        f"export const CAT_H = {SIZE};",
        "",
        "export const CAT_PALETTE: Record<string, string> = { '.': 'transparent', k: '#000000', w: '#ffffff' };",
        "",
        "type Sheet = 'sleep' | 'runRight' | 'runLeft' | 'sit' | 'wash' | 'alert' | 'scratch';",
        "",
        "export const CAT_FRAMES: Record<Sheet, string[][]> = {",
    ]
    for key, names in FRAMES.items():
        out.append(f"  {key}: [")
        for n in names:
            out.append(f"    // {n}")
            out.append("    [")
            out.extend(f"      '{r}'," for r in frame(root, n))
            out.append("    ],")
        out.append("  ],")
    out.append("};")
    out.append(
        """
function sheet(mode: CatMode, dir: 1 | -1): Sheet {
  if (mode === 'run') return dir === 1 ? 'runRight' : 'runLeft';
  return mode;
}

export function catFrame(mode: CatMode, dir: 1 | -1, frame: number): string[] {
  const frames = CAT_FRAMES[sheet(mode, dir)];
  return frames[frame % frames.length]!;
}"""
    )
    return "\n".join(out)


if __name__ == "__main__":
    root = Path(sys.argv[1])
    if len(sys.argv) > 2 and sys.argv[2] == "--preview":
        for n in sys.argv[3:]:
            print(f"== {n}")
            print("\n".join(r.replace(".", " ").replace("w", "·").replace("k", "#") for r in frame(root, n)))
    else:
        print(emit(root))
